export const getEpisodes = (seriesId, season) => {
  const seriesEps = episodesBySeries[seriesId]
  if (!seriesEps) return []
  if (season) return seriesEps[season] || []
  // return all episodes flattened
  return Object.values(seriesEps).flat()
}

export const getEpisodeById = (episodeId) => {
  for (const seriesEps of Object.values(episodesBySeries)) {
    for (const seasonEps of Object.values(seriesEps)) {
      const ep = seasonEps.find((e) => e.id === episodeId)
      if (ep) return ep
    }
  }
  return null
}

export const getNextEpisode = (currentEpisodeId) => {
  for (const seriesEps of Object.values(episodesBySeries)) {
    const allEps = Object.values(seriesEps).flat()
    const idx = allEps.findIndex((e) => e.id === currentEpisodeId)
    if (idx !== -1 && idx < allEps.length - 1) return allEps[idx + 1]
  }
  return null
}

export const getPrevEpisode = (currentEpisodeId) => {
  for (const seriesEps of Object.values(episodesBySeries)) {
    const allEps = Object.values(seriesEps).flat()
    const idx = allEps.findIndex((e) => e.id === currentEpisodeId)
    if (idx > 0) return allEps[idx - 1]
  }
  return null
}
